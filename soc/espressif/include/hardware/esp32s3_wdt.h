#define ESP32S3_RTC_CNTL_SWD_CONF_OFFSET     0x00b4U
#define ESP32S3_RTC_CNTL_SWD_WPROTECT_OFFSET 0x00b8U
#define ESP32S3_RTC_CNTL_STORE4_OFFSET       0x00c0U
#define ESP32S3_RTC_CNTL_STORE5_OFFSET       0x00c4U
#define ESP32S3_RTC_CNTL_PAD_HOLD_OFFSET     0x00d8U
#define ESP32S3_RTC_CNTL_DIG_PAD_HOLD_OFFSET 0x00dcU

// TIMG0/1 watchdog offsets match ESP32-C3
#define ESP32S3_TIMG_WDTCONFIG0_OFFSET  0x0048U
