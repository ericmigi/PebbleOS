#pragma once

#include <pbl/util/bits.h>

// ESP32-S3 SYSTEM peripheral (base 0x600c0000)
#define ESP32S3_SYSTEM_CPU_PER_CONF_OFFSET         0x0010U
#define ESP32S3_SYSTEM_PERIP_CLK_EN0_OFFSET        0x0018U
#define ESP32S3_SYSTEM_PERIP_CLK_EN1_OFFSET        0x001cU
#define ESP32S3_SYSTEM_PERIP_RST_EN0_OFFSET        0x0020U
#define ESP32S3_SYSTEM_PERIP_RST_EN1_OFFSET        0x0024U
#define ESP32S3_SYSTEM_CPU_INTR_FROM_CPU_OFFSET(n) (0x0030U + 4U * (n))
#define ESP32S3_SYSTEM_SYSCLK_CONF_OFFSET          0x0060U

// CPU_PER_CONF: PLL_FREQ_SEL (bit 2, 1=480MHz, 0=320MHz), CPUPERIOD_SEL [1:0] (0=80M, 1=160M,
// 2=240M)
#define ESP32S3_SYSTEM_CPU_PER_CONF_CPUPERIOD_SEL_MASK PBL_GENMASK(1, 0)
#define ESP32S3_SYSTEM_CPU_PER_CONF_PLL_FREQ_SEL       PBL_BIT(2)
#define ESP32S3_SYSTEM_CPUPERIOD_SEL_80M               0U
#define ESP32S3_SYSTEM_CPUPERIOD_SEL_160M              1U
#define ESP32S3_SYSTEM_CPUPERIOD_SEL_240M              2U

#define ESP32S3_SYSTEM_SYSCLK_CONF_PRE_DIV_CNT_MASK PBL_GENMASK(9, 0)
#define ESP32S3_SYSTEM_SYSCLK_CONF_SOC_CLK_SEL_MASK PBL_GENMASK(11, 10)
#define ESP32S3_SYSTEM_SOC_CLK_SEL_XTAL             0U
#define ESP32S3_SYSTEM_SOC_CLK_SEL_PLL              1U

// PERIP_CLK_EN0 / PERIP_RST_EN0 bits
#define ESP32S3_SYSTEM_PERIP_SPI2     PBL_BIT(6)
#define ESP32S3_SYSTEM_PERIP_I2C_EXT0 PBL_BIT(7)
#define ESP32S3_SYSTEM_PERIP_LEDC     PBL_BIT(11)
#define ESP32S3_SYSTEM_PERIP_SPI3     PBL_BIT(16)
#define ESP32S3_SYSTEM_PERIP_I2C_EXT1 PBL_BIT(18)
